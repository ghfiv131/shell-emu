"""Простой парсер командной строки эмулятора."""


def parse(line):
    """Разбить строку ввода на команду и список аргументов.

    Разделителем служат пробельные символы (пробелы и табуляции),
    несколько подряд идущих пробелов считаются одним разделителем.
    Кавычки и экранирование не поддерживаются.

    :param line: строка, введённая пользователем.
    :return: кортеж ``(command, args)`` или ``None`` для пустой строки.
    """
    parts = line.split()
    if not parts:
        return None
    return parts[0], parts[1:]
