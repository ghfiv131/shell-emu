#!/usr/bin/env sh
# Общие функции для тестовых скриптов: подключается через ". common.sh".
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
EMU="$ROOT/run.sh"

# run "описание" [аргументы эмулятора...]
# Запускает эмулятор с пустым stdin и печатает код возврата.
run() {
    title="$1"
    shift
    echo "================================================================"
    echo "### $title"
    echo "### ./run.sh $*"
    echo "----------------------------------------------------------------"
    "$EMU" "$@" < /dev/null
    echo "### exit code: $?"
    echo
}
